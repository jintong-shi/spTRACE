#!/usr/bin/env python3
"""Run a batch of simulations, sampling parameters from the [batch_ranges] table.

Console entry point: ``stcnv-batch``.

Each replicate gets its own design file (written to the replicate folder as
``config.toml``), is simulated in a subprocess, exported to Numbat allele-count
format, and summarised with QC figures.
"""

from __future__ import annotations

import argparse
import copy
import os
import random
import shutil
import subprocess
import sys

import matplotlib
import numpy as np

# Chosen before importing anything that touches pyplot, so replicates render
# without a display.
matplotlib.use("Agg")

from .. import _toml as toml  # noqa: E402

# Replicates run as subprocesses so that each simulation's peak memory is
# released before the next one starts.
SIMULATE_MODULE = "st_cnv_simulator.cli.simulate"
EXPORT_MODULE = "st_cnv_simulator.cli.export_numbat"

PATH_ALIASES = {
    # population
    "n_initial_cells": ("population", "n_initial_cells"),
    "max_cells": ("population", "max_cells"),
    "max_iter": ("population", "max_iterations"),
    "max_iterations": ("population", "max_iterations"),
    # tls
    "n_tls": ("tls", "n_tls"),
    "r_tls": ("tls", "r_tls"),
    # drip
    "immune_tls_share": ("drip", "immune_tls_share"),
    "per_cycle_max": ("drip", "per_cycle_max"),
    "every": ("drip", "every"),
    # weights
    "mu_s": ("weights", "mu_s"),
    "w_s": ("weights", "w_s"),
    "sigma_i": ("weights", "sigma_i"),
    "delta_epi": ("weights", "delta_epi"),
    "g_tls": ("weights", "g_tls"),
}

def sample_value(val_range):
    """Helper: Picks a random value from a [min, max] list."""
    if not isinstance(val_range, list) or len(val_range) != 2:
        return val_range

    min_v, max_v = val_range[0], val_range[1]

    if isinstance(min_v, int) and isinstance(max_v, int):
        return random.randint(min_v, max_v)
    elif isinstance(min_v, float) or isinstance(max_v, float):
        return round(random.uniform(min_v, max_v), 3)
    else:
        return val_range

def set_config_value(cfg, key, value):
    """
    Set a config value using a dot-path (e.g. "population.n_initial_cells")
    or a known alias in PATH_ALIASES. Falls back to top-level key.
    """
    if "." in key:
        path = key.split(".")
    elif key in PATH_ALIASES:
        path = list(PATH_ALIASES[key])
    else:
        cfg[key] = value
        return

    cur = cfg
    for part in path[:-1]:
        if part not in cur or not isinstance(cur[part], dict):
            cur[part] = {}
        cur = cur[part]
    cur[path[-1]] = value

def flatten_ranges(d, prefix=""):
    """
    Flatten nested dicts into dot-path keys.
    Example: {"population": {"n_initial_cells": [1,6]}} -> {"population.n_initial_cells": [1,6]}
    """
    out = {}
    for k, v in (d or {}).items():
        key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(flatten_ranges(v, key))
        else:
            out[key] = v
    return out

def perturb_celltype_proportions(base_props, concentration=50):
    """
    Apply Dirichlet perturbation to cell-type proportions.
    Higher concentration = less noise (tighter around base).
    concentration=50 gives ~10-20% relative variation per cell type.
    Returns dict with same keys, values sum to 1.
    """
    labels = list(base_props.keys())
    base_vals = np.array([base_props[k] for k in labels], dtype=float)
    # Dirichlet alpha = base_proportion * concentration
    alpha = base_vals * concentration
    alpha = np.maximum(alpha, 0.1)  # floor to avoid alpha=0 for tiny types
    sampled = np.random.dirichlet(alpha)
    return {k: round(float(v), 6) for k, v in zip(labels, sampled)}


def create_metadata_with_header(baf_dir):
    """
    Reads the headerless barcodes.tsv generated by run.py
    and saves a new metadata.tsv with a 'cell_id' header
    required by export_numbat.py.
    """
    raw_barcodes = os.path.join(baf_dir, "barcodes.tsv")
    clean_meta = os.path.join(baf_dir, "metadata.tsv")

    if os.path.exists(raw_barcodes):
        with open(raw_barcodes, 'r') as fin, open(clean_meta, 'w') as fout:
            fout.write("cell_id\n") # Add required header
            fout.write(fin.read())
        return clean_meta
    return None


def parse_args(argv=None):
    parser = argparse.ArgumentParser(
        prog="stcnv-batch",
        description="Run a batch of simulations with parameters sampled from [batch_ranges].",
    )
    parser.add_argument("--design", required=True, help="Path to the base design TOML file")
    parser.add_argument(
        "--output",
        default=None,
        help="Batch output directory; defaults to [batch].output_folder in the design file",
    )
    parser.add_argument(
        "--replicates",
        type=int,
        default=None,
        help="Number of replicates; defaults to [batch].replicates in the design file",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Seed for the batch-level parameter sampler. Overrides [batch].seed. "
        "The same seed reproduces the whole batch, including each replicate's own seed.",
    )
    parser.add_argument(
        "--no-parquet",
        action="store_true",
        help="Pass --no-parquet to every replicate (writes TSV instead of Parquet)",
    )
    parser.add_argument(
        "--skip-visual", action="store_true", help="Pass --skip-visual to every replicate"
    )
    parser.add_argument(
        "--jobs", type=int, default=1, help="Pass --jobs to every replicate (default 1)"
    )
    parser.add_argument(
        "--genetic-map",
        default=None,
        help="Genetic map for the Numbat export; without it, the export step is skipped",
    )
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    design_file = args.design

    if not os.path.exists(design_file):
        print(f"Error: {design_file} not found.")
        return 1

    print(f"Reading configuration from {design_file}...")
    with open(design_file) as f:
        config = toml.load(f)

    if "batch" not in config or "batch_ranges" not in config:
        print(f"Error: [batch] or [batch_ranges] section missing in {design_file}")
        return 1

    batch_meta = config["batch"]
    ranges = flatten_ranges(config["batch_ranges"])

    n_reps = args.replicates if args.replicates is not None else batch_meta.get("replicates", 1)
    base_out = args.output or batch_meta.get("output_folder", "Batch_Output")
    os.makedirs(base_out, exist_ok=True)

    # Seed the batch-level sampler so the full set of replicate parameters --
    # and each replicate's own simulation seed -- is reproducible.
    batch_seed = args.seed if args.seed is not None else batch_meta.get("seed")
    if batch_seed is None:
        print("WARNING: no batch seed ([batch].seed or --seed); replicate parameters "
              "will differ between runs of this command.")
    else:
        batch_seed = int(batch_seed)
        random.seed(batch_seed)
        np.random.seed(batch_seed)
        print(f"Batch sampler seed set to {batch_seed}")

    print(f"--- Starting Batch: {n_reps} replicates ---")

    for i in range(1, n_reps + 1):
        run_config = copy.deepcopy(config)

        # Clean up batch keys from the run config
        if "batch" in run_config: del run_config["batch"]
        if "batch_ranges" in run_config: del run_config["batch_ranges"]

        # --- 1. Sample Standard Parameters ---
        sampled_log = {}
        for param, val_range in ranges.items():
            # Skip special CNV keys
            if param in ["n_shared_count", "n_private_count"]:
                continue

            val = sample_value(val_range)
            set_config_value(run_config, param, val)
            sampled_log[param] = val

        # --- 1b. Randomize reproducibility seed per replicate ---
        seed_val = random.randint(1, 2**31 - 1)
        set_config_value(run_config, "reproducibility.seed", seed_val)
        sampled_log["reproducibility.seed"] = seed_val

        # --- 1c. Perturb normal_celltype_proportions ---
        base_props = config.get("normal_celltype_proportions", {})
        if base_props:
            perturbed = perturb_celltype_proportions(base_props)
            run_config["normal_celltype_proportions"] = perturbed
            sampled_log["normal_celltype_proportions"] = perturbed

        # --- 2. Handle [initial_cnv] Logic ---
        n_clones = run_config.get("population", {}).get("n_initial_cells", 5)

        shared_rng = ranges.get("n_shared_count", [2, 6])
        private_rng = ranges.get("n_private_count", [1, 4])

        val_shared = sample_value(shared_rng)
        # Generate list matching n_initial_cells length
        val_private_list = [sample_value(private_rng) for _ in range(n_clones)]

        run_config["initial_cnv"] = {
            "n_shared": val_shared,
            "n_private": val_private_list
        }

        sampled_log["n_shared"] = val_shared
        sampled_log["n_private"] = val_private_list

        # --- 3. Run Simulation ---
        rep_folder = os.path.join(base_out, f"Rep_{i}_Clones_{n_clones}_Shared_{val_shared}")
        temp_design_path = os.path.join(base_out, f"design_run_{i}.toml")

        with open(temp_design_path, 'w') as f:
            toml.dump(run_config, f)

        print(f"\n[Run {i}/{n_reps}] Clones: {n_clones} | Shared: {val_shared}")

        cmd_run = [
            sys.executable, "-m", SIMULATE_MODULE,
            "--design", temp_design_path,
            "--output", rep_folder,
            "--overwrite",
        ]
        if args.no_parquet:
            cmd_run.append("--no-parquet")
        if args.skip_visual:
            cmd_run.append("--skip-visual")
        cmd_run += ["--jobs", str(args.jobs)]


        try:
            # A. Execute run.py
            subprocess.run(cmd_run, check=True)
            shutil.move(temp_design_path, os.path.join(rep_folder, "config.toml"))

            # B. Export to Numbat allele-count format
            if args.genetic_map:
                baf_dir = os.path.join(rep_folder, "baf")

                # Numbat needs a header on the barcode list.
                meta_path = create_metadata_with_header(baf_dir)

                if meta_path:
                    snp_path = os.path.join(baf_dir, "snp_info.csv")
                    numbat_out = os.path.join(rep_folder, "numbat_allele_counts.tsv.gz")

                    print(f"   -> Exporting Numbat: {numbat_out}")
                    cmd_export = [
                        sys.executable, "-m", EXPORT_MODULE,
                        "--baf-dir", baf_dir,
                        "--snp-file", snp_path,
                        "--meta-file", meta_path,
                        "--genetic-map", args.genetic_map,
                        "--output", numbat_out,
                    ]
                    subprocess.run(cmd_export, check=True)
                else:
                    print("   [Warning] barcodes.tsv not found, skipping Numbat export.")

            # QC figures, including the subclone panels, are written by
            # stcnv-simulate itself -- see st_cnv_simulator.qc.

        except subprocess.CalledProcessError as e:
            print(f"Error in Run {i}: {e}")

    print("\n--- Batch Completed ---")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
